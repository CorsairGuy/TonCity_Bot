# Штаб-квартира полиции, ночь (18.10.2026): синий неон ровно по рисунку пользователя — двойной контур крыши
# с рамкой вокруг таблички POLICE; огни по кругу вертолётной площадки (не поверх вертолёта), разметка «H»
# подсвечена; светятся окна КПП. Огней на вертолёте и пятна у лестницы нет. Окна здания и подсветка таблички
# POLICE — прежние ключи разметки, этот модуль добавляется к ним через {"t":"mod","mod":"police_hq"}.
import numpy as np
from scipy import ndimage as nd
from .common import parts, halo, edge, shaded, lines
from .neonkit import neon, bulbs, spotg, poly, ell_pts, region

BL = (60, 120, 255); WH = (235, 240, 255); GRN = (110, 255, 140); WARM = (255, 200, 140)
# линии неона, снятые с рисунка пользователя (родной размер кадра)
SEGS = [((593.8, 128.0), (436.4, 31.3)), ((434.1, 217.7), (593.8, 128.0)), ((449.3, 178.6), (300.1, 90.2)),
        ((545.0, 106.8), (415.2, 33.1)), ((300.1, 90.2), (415.2, 19.3)), ((429.9, 188.7), (325.9, 130.7)),
        ((478.7, 182.3), (574.5, 124.3)), ((319.5, 90.2), (415.2, 33.1)), ((390.3, 195.2), (314.9, 154.7)),
        ((418.0, 211.7), (349.8, 174.9)), ((574.5, 124.3), (534.0, 99.4)), ((448.3, 197.9), (478.7, 182.3)),
        ((434.1, 217.7), (429.9, 188.7)), ((344.3, 105.0), (319.5, 90.2)), ((448.3, 197.9), (449.3, 178.6)),
        ((325.9, 130.7), (333.3, 114.2)), ((316.7, 143.6), (318.5, 127.0))]
CX, CY, RX, RY = 405.5, 71, 36, 15.5             # вертолётная площадка


def emit(im, name):
    rgb, a, L, Y, X = parts(im); sh = a.shape
    sol = a > 200
    # вертолёт: корпус и хвост над площадкой, тёмные лопасти; на нём свет не рисуется
    heli = sol & (poly(sh, [(372, 22), (452, 22), (452, 66), (380, 66)]) | poly(sh, [(440, 52), (492, 62), (492, 90), (445, 86)])) \
        & ~((np.abs(L - 171) < 6) | (L > 205) | (np.abs(L - 214) < 5))
    heli |= sol & (L < 90) & poly(sh, [(340, 0), (520, 0), (520, 95), (340, 95)])
    heli = nd.binary_closing(heli, np.ones((3, 3)))
    HD = nd.binary_dilation(heli, iterations=3)
    e = neon((lines(sh, SEGS, 2.0) > 0.4) & ~HD, BL, 1.2)
    # огни по кругу площадки: зелёные и белые через один
    pts = [p for p in ell_pts(CX, CY, RX * 1.18, RY * 1.18, 20) if not HD[p[1], p[0]]]
    e += bulbs(sh, X, Y, pts[0::2], GRN, 2.3) + bulbs(sh, X, Y, pts[1::2], WH, 2.3)
    # разметка площадки (кольцо и «H») и край площадки
    E = ((X - CX) / RX) ** 2 + ((Y - CY) / RY) ** 2
    disc = (E < 1.05) & sol & ~HD
    p = shaded(disc & (L > 170), (200, 225, 255), L, lo=0.8, k=0.55)
    p += neon(edge(E < 1.0, 1) & sol & ~HD, (200, 225, 255), 0.5, ((0.5, 2), (0.2, 6)))
    e += halo(p, [(0.5, 2), (0.25, 6)])
    # КПП: полоса стёкол под крышей будки, по три окна на сторону
    booth = region(rgb, a, 270, 350, 10)
    bw = sol & poly(sh, [(234, 358), (267, 374), (306, 354), (306, 388), (267, 404), (234, 388)]) & ~booth & (L > 150)
    u = np.where(X < 267, (X - 234) / 33, (X - 267) / 39)
    frames = (np.abs((u * 3) % 1 - 0.5) > 0.38) | (np.abs(u) < 0.05) | (np.abs(u - 1) < 0.05)
    bg = bw & ~frames & ~edge(bw, 2)
    e += halo(shaded(bg, WARM, L, lo=0.7, k=0.5) + spotg(X, Y, 262, 415, 50, WARM, 0.22), [(0.5, 2), (0.25, 6)])
    return e
