'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../..');
const {mergeObserved}=require(path.join(root,'src/utils/buildingCatalog'));
const esbuild=require(path.join(root,'src/web/client/node_modules/esbuild'));
const code=fs.readFileSync(path.join(root,'src/web/client/src/cityStats.ts'),'utf8');
const ctx={module:{exports:{}}};vm.runInNewContext(esbuild.transformSync(code,{loader:'ts',format:'cjs'}).code,ctx);
const {statsCatalog,computeCityStats}=ctx.module.exports;
const catalog=JSON.parse(fs.readFileSync(path.join(root,'config/buildings.txt'),'utf8'));
const ids=['RES_crystal_aurora_1_star.png','SER_botanical_garden_1_star.png','COM_bank_2_star.png'];
const missing=ids.map(id=>{const b=catalog.find(x=>x.id===id);assert(b,`${id} отсутствует в резервном каталоге`);return b;});
const live=catalog.filter(b=>!ids.includes(b.id));
const same={...live[0],base_price:123};
const merged=mergeObserved([same,...missing],[{...same,base_price:456}]);
assert.equal(merged.find(b=>b.id===same.id).base_price,456);
for(const id of ids)assert(merged.some(b=>b.id===id));
const statsMap=statsCatalog(live,missing);
const buildings=ids.map((id,i)=>({id,level:10,x:i,y:0}));
const without=computeCityStats(buildings,new Map(live.map(b=>[b.id,b]))),withFallback=computeCityStats(buildings,statsMap);
assert.equal(without.population,0);assert(withFallback.population>0);
assert.equal(without.coverageByCat.park,0);assert(withFallback.coverageByCat.park>0);
assert.equal(without.profit,0);assert(withFallback.profit>0);
const liveWins=statsCatalog([{id:'test',base_price:42}],[{id:'test',base_price:1}]);assert.equal(liveWins.get('test').base_price,42);
assert.equal(live.some(b=>ids.includes(b.id)),false,'резервные записи не попадают в каталог действий');
console.log('PASS partial building catalogs: retained game records, live priority, missing starred buildings in statistics, action catalog unchanged');
